namespace HeroDefense.Campaign
{
    /// <summary>
    /// Кто нападает на владение.
    ///
    /// Фракция — обещание игроку: увидев её на карте, он должен понимать,
    /// к чему готовиться. Быстрые звери и медленная живучая нежить требуют
    /// разной обороны, и в этом смысл выбора на развилке.
    ///
    /// В прототипе реализованы не все — важно, чтобы структура позволяла
    /// добавлять их без переделки.
    ///
    /// Значения пишутся в сохранение числом: порядок не менять,
    /// новые фракции только в конец.
    /// </summary>
    public enum EnemyFaction
    {
        /// <summary>Бандиты: базовая угроза, ничем не выдающаяся.</summary>
        Bandits = 0,

        /// <summary>Звери: быстрые, низкий силуэт, идут густо.</summary>
        Beasts = 1,

        /// <summary>Чудища: редкие и тяжёлые, каждое — событие.</summary>
        Monsters = 2,

        /// <summary>Нежить: медленная, но живучая, давит числом.</summary>
        Undead = 3,

        /// <summary>Викинги: набеги с моря. Уместны у портов.</summary>
        Vikings = 4,

        /// <summary>
        /// Войско соседнего феодала: строй, тяжёлая пехота, свои командиры.
        /// Именно эта фракция отличает игру от обороны от монстров —
        /// вассалов разоряют не только чудовища, но и соседи.
        /// </summary>
        RivalLord = 5
    }
}
