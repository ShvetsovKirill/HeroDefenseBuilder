namespace HeroDefense.Campaign
{
    /// <summary>
    /// Тип владения на карте кампании.
    ///
    /// Задаёт три вещи разом: сколько идёт бой, что защищаем и какую
    /// награду дают. Поэтому тип — не украшение, а главный параметр
    /// владения: по нему игрок выбирает, куда свернуть на развилке.
    ///
    /// Значения пишутся в сохранение числом — порядок менять нельзя,
    /// новые типы только в конец.
    /// </summary>
    public enum HoldingKind
    {
        /// <summary>Село: короткий бой, немного престижа. Место передышки.</summary>
        Village = 0,

        /// <summary>Деревня: бой подлиннее, престиж и мелкая награда.</summary>
        Town = 1,

        /// <summary>Портовый городок: средний бой, усиление отряда или короля.</summary>
        Port = 2,

        /// <summary>Баронство: тяжёлый бой с боссом, в награду новый командир.</summary>
        Barony = 3,

        /// <summary>Замок: самый длинный бой, крупная награда.</summary>
        Castle = 4,

        /// <summary>Походный лагерь: чужой обоз или стоянка, средний бой.</summary>
        WarCamp = 5
    }
}
